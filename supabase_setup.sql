-- 5. ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- 6. POLICIES FOR PUBLIC (ANON) ACCESS
CREATE POLICY "Allow public read on matches"
ON public.matches FOR SELECT USING (true);

CREATE POLICY "Allow public update on matches"
ON public.matches FOR UPDATE USING (true) WITH CHECK (true);

CREATE POLICY "Allow public read on bookings"
ON public.bookings FOR SELECT USING (true);

CREATE POLICY "Allow public insert on bookings"
ON public.bookings FOR INSERT WITH CHECK (true);

-- 7. ENABLE REALTIME ON MATCHES AND BOOKINGS
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'matches'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.matches;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'bookings'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.bookings;
  END IF;
END $$;
